package main

import (
	"fmt"
	"sort"
	"strings"

	"github.com/JayveerPrajapati/kern/internal/diffgate"
	mcp "github.com/JayveerPrajapati/kern/internal/mcp"
	"github.com/JayveerPrajapati/kern/internal/mcp/toolsurface"
)

// generateToolSelectionDoc renders docs/tool-selection.md from the live
// catalog, default surface, and legacy high-level surface. Every count and
// tool name is derived from code — no hand-maintained numbers.
func generateToolSelectionDoc(tools []diffgate.ToolInfo) ([]byte, error) {
	if len(tools) == 0 {
		return nil, fmt.Errorf("no MCP tool catalog injected")
	}

	sorted := append([]diffgate.ToolInfo(nil), tools...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	byName := make(map[string]diffgate.ToolInfo, len(sorted))
	for _, t := range sorted {
		byName[t.Name] = t
	}

	defaultNames := toolsurface.Default
	defaultSet := toolsurface.Set()
	for _, name := range defaultNames {
		if _, ok := byName[name]; !ok {
			return nil, fmt.Errorf("default-surface tool %q missing from live catalog", name)
		}
	}

	var fullOnly []diffgate.ToolInfo
	for _, t := range sorted {
		if !defaultSet[t.Name] {
			fullOnly = append(fullOnly, t)
		}
	}

	riskCounts := map[string]int{
		"low":      0,
		"medium":   0,
		"high":     0,
		"critical": 0,
	}
	for _, t := range sorted {
		if _, ok := riskCounts[t.RiskLevel]; !ok {
			return nil, fmt.Errorf("unknown risk level %q for tool %q", t.RiskLevel, t.Name)
		}
		riskCounts[t.RiskLevel]++
	}

	highLevelCount := mcp.HighLevelToolsCount()

	var b strings.Builder
	b.WriteString("<!-- Generated by `kern gen-docs --doc selection` — do not edit by hand. -->\n")
	b.WriteString("# Tool Selection Guide\n\n")
	b.WriteString("> Generated from [`internal/mcpcatalog/tools.go`](../internal/mcpcatalog/tools.go),\n")
	b.WriteString("> [`internal/mcp/toolsurface/toolsurface.go`](../internal/mcp/toolsurface/toolsurface.go), and\n")
	b.WriteString("> [`internal/mcp/toolpolicy.go`](../internal/mcp/toolpolicy.go).\n")
	b.WriteString("> If this guide and those files disagree, those files win.\n\n")
	fmt.Fprintf(&b, "kern ships a **%d-tool** MCP catalog and advertises the **full catalog by default** (standing mandate 2026-10-23: agents use all available tools). Every tool is advertised on `tools/list`; `kern_meta` routes natural language to any of them.\n\n", len(sorted))

	b.WriteString("## Surface\n\n")
	b.WriteString("| Mode | Tools |\n|---|---:|\n")
	fmt.Fprintf(&b, "| Default | %d |\n", len(defaultNames))
	fmt.Fprintf(&b, "| Full (`KERN_MCP_FULL=1`) | %d |\n", len(sorted))
	b.WriteString("| Router-only (`KERN_MCP_SINGLE_TOOL=1`) | 1 |\n")
	fmt.Fprintf(&b, "| High-level (`KERN_MCP_HIGH_LEVEL_ONLY=1`) | %d |\n", highLevelCount)
	b.WriteString("| Phase filter (`KERN_MCP_PHASE`) | Default/full subset plus `meta` and `cross` tools |\n")
	b.WriteString("| Category filter (`KERN_MCP_CATEGORY`) | One category plus `kern_meta` |\n")
	b.WriteString("| Allowlist (`KERN_TOOLS`) | Execution gate applied on every call |\n\n")

	b.WriteString("The default surface is:\n\n")
	for i, name := range defaultNames {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString("`" + name + "`")
	}
	b.WriteString(".\n\n")
	b.WriteString("`kern_exec` is advertised for discoverability only. Every execution attempt still fails closed unless explicitly enabled through `KERN_ALLOW_EXEC` or an allowlist policy.\n\n")

	b.WriteString("## Choose by intent\n\n")
	b.WriteString("| Intent | Best tool | Why |\n|---|---|---|\n")
	b.WriteString("| New repo or unfamiliar project | `kern_buddy` | Onboarding digest, layout, conventions, memory |\n")
	b.WriteString("| Find a symbol by name | `kern_search` | Ranked symbol lookup |\n")
	b.WriteString("| Structural pattern (`func greet`, `type *User*`) | `kern_ast_search` | AST-aware search |\n")
	b.WriteString("| Understand one symbol deeply | `kern_explore` | Definition, callers, callees, blast radius |\n")
	b.WriteString("| Need only the exact source slice | `kern_context` | Minimal definition and direct edges |\n")
	b.WriteString("| Understand a file's structure | `kern_compact_file` | Functions, types, line numbers; `tier=full` for verbatim |\n")
	b.WriteString("| Explain why a symbol matters | `kern_why` | Rationale, docs, dependency counts |\n")
	b.WriteString("| Plan a change | `kern_plan` | Deterministic affected files, risks, validation |\n")
	b.WriteString("| Pre-select context for a change | `kern_plan_context` | Avoids over-fetching |\n")
	b.WriteString("| Fit selected files/symbols in a token budget | `kern_fit_context` | Tiered AST folding |\n")
	b.WriteString("| Assess blast radius | `kern_impact` | Change impact analysis |\n")
	b.WriteString("| Review changed files | `kern_review` | Token-optimized review context |\n")
	b.WriteString("| Run verification | `kern_verify` | Build/tests/security checks and command slices |\n")
	b.WriteString("| Self-correct failing files | `kern_heal` | Validation loop in a throwaway snapshot |\n")
	b.WriteString("| Whole-project map | `kern_project_map` | File/symbol map |\n")
	b.WriteString("| Search project docs | `kern_doc` (`action=search`) | Local doc index |\n")
	b.WriteString("| Remember or recall project lessons | `kern_memory` | Cross-session project memory |\n")
	b.WriteString("| Compress a prompt, log, or output | `kern_optimize` | Token reduction and masking |\n")
	b.WriteString("| Mask secrets/PII | `kern_mask_pii` | Local-only scan |\n")
	b.WriteString("| Inspect semantic cache | `kern_semcache` | Stats/list/clear/similarity |\n")
	b.WriteString("| Re-read truncated output | `kern_fetch_raw_anchor` | Full retained output slices |\n")
	b.WriteString("| Find a call path | `kern_path` | Shortest in-project call route |\n")
	b.WriteString("| Run a full intent pipeline | `kern_run` | Explore/plan/edit/verify orchestration |\n")
	b.WriteString("| Produce signed evidence | `kern_evidence` | Verify/explain/export/anchor |\n")
	b.WriteString("| Swap code blocks with symbolic signatures | `kern_swap` | Context compression |\n")
	b.WriteString("| Unsure which tool to call | `kern_meta` | Natural-language router |\n\n")

	b.WriteString("## Full-catalog tools\n\n")
	b.WriteString("| Tool | Purpose |\n|---|---|\n")
	for _, t := range fullOnly {
		desc := strings.ReplaceAll(t.Description, "\n", " ")
		fmt.Fprintf(&b, "| `%s` | %s |\n", t.Name, desc)
	}
	b.WriteString("\n")

	b.WriteString("## Risk model\n\n")
	b.WriteString("| Risk | Count | Meaning |\n|---|---:|---|\n")
	fmt.Fprintf(&b, "| low | %d | Read-only or locally contained operations |\n", riskCounts["low"])
	fmt.Fprintf(&b, "| medium | %d | Analysis, planning, memory, docs, verification |\n", riskCounts["medium"])
	fmt.Fprintf(&b, "| high | %d | Orchestration and self-repair |\n", riskCounts["high"])
	fmt.Fprintf(&b, "| critical | %d | Governed command execution |\n\n", riskCounts["critical"])

	b.WriteString("## Principles\n\n")
	b.WriteString("1. Start with `kern_buddy` for onboarding or `kern_meta` when the intent is already known.\n")
	b.WriteString("2. Prefer the narrowest useful tool: `kern_context` before `kern_explore`, and `kern_compact_file` before reading a whole file.\n")
	b.WriteString("3. Use `kern_plan` or `kern_plan_context` before edits.\n")
	b.WriteString("4. Use `kern_review` and `kern_verify` after edits.\n")
	b.WriteString("5. Treat `kern_exec` as an explicitly governed capability, never as an ordinary fallback.\n")

	return []byte(b.String()), nil
}
