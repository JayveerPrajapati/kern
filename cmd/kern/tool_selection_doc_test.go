package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/JayveerPrajapati/kern/internal/diffgate"
	"github.com/JayveerPrajapati/kern/internal/mcp/toolsurface"
)

func selectionTestCatalog() []diffgate.ToolInfo {
	names := append([]string(nil), toolsurface.Default...)
	names = append(names, "kern_graph", "kern_arch")
	tools := make([]diffgate.ToolInfo, 0, len(names))
	for i, name := range names {
		risk := "low"
		switch {
		case i%13 == 0:
			risk = "medium"
		case i%17 == 0:
			risk = "high"
		case i == 0:
			risk = "critical"
		}
		tools = append(tools, diffgate.ToolInfo{
			Name:        name,
			Phase:       "explore",
			RiskLevel:   risk,
			Description: "test tool",
		})
	}
	return tools
}

func TestGenerateToolSelectionDocDerivesCatalogCounts(t *testing.T) {
	tools := selectionTestCatalog()
	diffgate.SetToolInfos(tools)
	doc, err := generateToolSelectionDoc(tools)
	if err != nil {
		t.Fatal(err)
	}
	text := string(doc)
	for _, want := range []string{
		"**31-tool** MCP catalog",
		"**29 tools by default**",
		"`kern_graph`",
		"`kern_arch`",
		"Generated by `kern gen-docs --doc selection`",
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("selection doc missing %q", want)
		}
	}
}

func TestGenDocsSelectionCheckFreshAndStale(t *testing.T) {
	root := t.TempDir()
	tools := selectionTestCatalog()
	diffgate.SetToolInfos(tools)
	docPath := filepath.Join(root, "docs", "tool-selection.md")
	if err := os.MkdirAll(filepath.Dir(docPath), 0o755); err != nil {
		t.Fatal(err)
	}
	expected, err := generateToolSelectionDoc(tools)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(docPath, expected, 0o644); err != nil {
		t.Fatal(err)
	}
	runGenDocsImpl([]string{"--root", root, "--doc", "selection", "--check"}, "gen-docs", "", true)

	stale := []byte("stale selection guide")
	if err := os.WriteFile(docPath, stale, 0o644); err != nil {
		t.Fatal(err)
	}
	expectExit(t, 1, func() {
		runGenDocsImpl([]string{"--root", root, "--doc", "selection", "--check"}, "gen-docs", "", true)
	})
	after, err := os.ReadFile(docPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != string(stale) {
		t.Fatal("selection --check must not rewrite a stale file")
	}
}

func TestGenDocsSelectionRegeneratesStaleGuide(t *testing.T) {
	root := t.TempDir()
	tools := selectionTestCatalog()
	diffgate.SetToolInfos(tools)
	docPath := filepath.Join(root, "docs", "tool-selection.md")
	if err := os.MkdirAll(filepath.Dir(docPath), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(docPath, []byte("stale selection guide"), 0o644); err != nil {
		t.Fatal(err)
	}
	runGenDocsImpl([]string{"--root", root, "--doc", "selection"}, "gen-docs", "", true)
	got, err := os.ReadFile(docPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "**31-tool** MCP catalog") {
		t.Fatalf("regenerated selection guide is missing the derived catalog count:\n%s", got)
	}
}
