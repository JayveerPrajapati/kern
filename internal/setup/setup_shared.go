// instructionFiles maps each agent to its project-level instruction file
// that receives the kern-first policy. These files are git-ignored when
// generated by setup (they carry machine-specific paths or are redundant
// with the universal AGENTS.md). Cursor's policy lives in its rules dir
// (.cursor/rules/kern.mdc — the project analog of the global
// ~/.cursor/rules/kern.mdc), the only location Cursor loads rules from.
var instructionFiles = map[string]string{
	"claude":      "CLAUDE.md",
	"gemini":      "GEMINI.md",
	"antigravity": ".agents/rules/kern.md",
	"copilot":     ".github/copilot-instructions.md",
	"cursor":      ".cursor/rules/kern.mdc",
}

// legacyInstructionFiles lists instruction-file paths written by older kern
// releases and since superseded. Check accepts them as a valid install (a
// legacy file still carries the kern-first policy — doctor must not warn
// about a file the current setup no longer writes), and wireInstructions
// migrates a legacy file that holds nothing but the kern-managed block.
var legacyInstructionFiles = map[string]string{
	"cursor": ".cursor/instructions/kern.mdc",
}

// DetectAgents scans the project root and system PATH for evidence that each
// known agent is in use. Returns the list of detected agent names.
func DetectAgents(root string) []string {
	var detected []string
	for _, d := range agentDetectors {
		if isAgentPresent(root, d) {
			detected = append(detected, d.agent)
		}
	}
	return detected
}

func isAgentPresent(root string, d agentDetector) bool {
	for _, p := range d.paths {
		var path string
		if strings.HasPrefix(p, "~") {
			path = homeJoin(strings.TrimPrefix(p, "~"))
		} else {
			path = filepath.Join(root, p)
		}
		if _, err := os.Stat(path); err == nil {
			return true
		}
	}
	if d.binary != "" {
		if _, err := exec.LookPath(d.binary); err == nil {
			return true
		}
	}
	return false
}

// wireInstructions writes the kern-first policy block into each detected
// agent's instruction file, creating the file if missing. Each written
// file receives an idempotency marker so re-running setup doesn't duplicate.
func wireInstructions(root string, agents []string) []Status {
	rules, err := rulesFS.ReadFile("assets/AGENTS.md")
	if err != nil {
		return []Status{{Agent: "instructions", Note: err.Error()}}
	}
	rulesText := string(rules)
	var out []Status
	for _, agent := range agents {
		file, ok := instructionFiles[agent]
		if !ok {
			continue
		}
		path := filepath.Join(root, file)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			out = append(out, Status{Agent: agent + "-instruction", Note: err.Error()})
			continue
		}
		status := writeInstructionFile(path, rulesText)
		status.Agent = agent + "-instruction"
		out = append(out, status)
		// Migrate a superseded path (e.g. the pre-F10
		// .cursor/instructions/kern.mdc) so the policy lives in exactly
		// one place once the current path is written.
		if legacy, ok := legacyInstructionFiles[agent]; ok {
			out = append(out, migrateLegacyInstruction(root, agent, legacy, path)...)
		}
	}
	return out
}

// migrateLegacyInstruction removes a superseded instruction file after the
// current one was written. A legacy file that holds user content outside
// the kern-managed block is left in place (Check still accepts it); only a
// file that is nothing but the managed block is deleted.
func migrateLegacyInstruction(root, agent, legacy, current string) []Status {
	lp := filepath.Join(root, legacy)
	if lp == current {
		return nil
	}
	b, err := os.ReadFile(lp)
	if err != nil {
		return nil // no legacy install — nothing to migrate
	}
	cleaned := strutil.RemoveMarkedBlock(string(b), instructionMarkerOpen, instructionMarkerClose)
	if cleaned, err = removeKernSection(cleaned); err != nil {
		return nil // cannot tell whether the file is kern-only — leave it in place
	}
	if strings.TrimSpace(cleaned) != "" {
		return []Status{{Agent: agent + "-legacy", Installed: true, Path: lp, Note: "legacy instruction file has user content — left in place (still accepted)"}}
	}
	if err := os.Remove(lp); err != nil {
		return []Status{{Agent: agent + "-legacy", Path: lp, Note: err.Error()}}
	}
	_ = os.Remove(filepath.Dir(lp)) // best effort: drop the now-empty dir
	return []Status{{Agent: agent + "-legacy", Installed: true, Path: lp, Note: "migrated legacy " + legacy + " to " + current}}
}

// instructionPolicyPresent reports whether path exists and carries the
// kern-first policy: the managed marker block or the unmarked rules
// section. This is the probe Check uses for per-agent instruction status.
func instructionPolicyPresent(path string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	return strings.Contains(string(b), "kern usage rules") || strings.Contains(string(b), "kern-instruction:")
}

// writePerm returns the permission bits to use when writing a config-like
// file. Existing files keep their current permissions (configs with tokens are
// often 0600 and must not be widened); new files default to 0600.
func writePerm(path string) os.FileMode {
	if info, err := os.Stat(path); err == nil {
		return info.Mode().Perm()
	}
	return 0o600
}

// instructionMarkerOpen / instructionMarkerClose bracket the kern-managed block
// in a per-agent instruction file (CLAUDE.md, GEMINI.md, etc.). They let us
// remove-and-rewrite the block on every setup run so an upgrade always writes
// fresh rules rather than skipping when stale rules are detected.
const (
	instructionMarkerOpen  = "<!-- kern-instruction: managed by kern setup; do not edit between markers -->"
	instructionMarkerClose = "<!-- /kern-instruction -->"
)

// writeInstructionFile writes the kern-first policy block to a single
// instruction file. On every run it removes any existing kern-managed block
// (between instructionMarkerOpen and instructionMarkerClose) and re-inserts
// the fresh embedded rules, preserving all user content outside the block.
// This is overwrite-always: an upgrade with new rules always replaces the old
// block rather than skipping when a marker is present.
// The same per-agent files (CLAUDE.md, GEMINI.md, …) can also be written by
// wireRulesFile using an unmarked kern section. To avoid duplicate blocks when
// both paths run, writeInstructionFile strips BOTH the marked instruction
// block AND any unmarked kern section before re-inserting.
func writeInstructionFile(path, rulesText string) Status {
	cur, _ := os.ReadFile(path)
	content := string(cur)
	cleaned := strutil.RemoveMarkedBlock(content, instructionMarkerOpen, instructionMarkerClose)
	cleaned, err := removeKernSection(cleaned)
	if err != nil {
		return Status{Agent: "", Path: path, Note: err.Error()}
	}
	block := instructionMarkerOpen + "\n\n" + strings.TrimRight(rulesText, "\n") + "\n\n" + instructionMarkerClose
	var joined string
	if strings.TrimSpace(cleaned) == "" {
		joined = block + "\n"
	} else {
		joined = strings.TrimRight(cleaned, "\n") + "\n\n" + block + "\n"
	}
	joined = ensureInstructionFrontmatter(path, joined)
	if err := os.WriteFile(path, []byte(joined), writePerm(path)); err != nil {
		return Status{Agent: "", Path: path, Note: err.Error()}
	}
	return Status{Agent: "", Installed: true, Path: path, Note: "kern-first policy written"}
}

// ensureInstructionFrontmatter guarantees a Cursor .mdc rule file carries
// the YAML frontmatter Cursor requires on line 1, outside the managed
// markers — without it Cursor will not load the rule at all. Same contract
// as the global path's ensureMDCFrontmatter, but keyed on the project
// instruction markers. Idempotent: a file that already has the frontmatter
// ahead of the markers is returned byte-for-byte unchanged.
func ensureInstructionFrontmatter(path, content string) string {
	if !strings.HasSuffix(path, ".mdc") {
		return content
	}
	if marker := strings.Index(content, instructionMarkerOpen); marker >= 0 &&
		strings.Contains(content[:marker], cursorFrontmatter) {
		return content
	}
	return cursorFrontmatter + "\n\n" + content
}

// wireRulesFile writes the embedded kern rules block to a single rule file
// (AGENTS.md). On every run it removes any existing kern section and re-inserts
// the fresh embedded rules, preserving all user content outside the block.
// This is overwrite-always: an upgrade with new rules always replaces the old
// block rather than skipping when a "kern usage rules" header is present.
// The same per-agent files (CLAUDE.md, GEMINI.md, …) can also be written by
// writeInstructionFile using a marked block (instructionMarkerOpen/Close).
// To avoid duplicate blocks when both paths run, wireRulesFile strips BOTH the
// unmarked kern section AND any marked instruction block before re-inserting.
func wireRulesFile(root, name string) Status {
	path := filepath.Join(root, name)
	content := ""
	if b, err := os.ReadFile(path); err == nil {
		content = string(b)
	}
	rules, err := rulesFS.ReadFile("assets/AGENTS.md")
	if err != nil {
		return Status{Agent: name, Path: path, Note: err.Error()}
	}
	cleaned := strutil.RemoveMarkedBlock(content, instructionMarkerOpen, instructionMarkerClose)
	cleaned, err = removeKernSection(cleaned)
	if err != nil {
		return Status{Agent: name, Path: path, Note: err.Error()}
	}
	// If the block is unchanged (same content after remove+reinsert), skip the
	// write to avoid needlessly bumping mtime. This mirrors the global path.
	final, err := mergeAppend(cleaned, string(rules))
	if err != nil {
		return Status{Agent: name, Path: path, Note: err.Error()}
	}
	if content != "" && final == content {
		return Status{Agent: name, Installed: true, Path: path, Note: "rules already current"}
	}
	if err := os.WriteFile(path, []byte(final), writePerm(path)); err != nil {
		return Status{Agent: name, Path: path, Note: err.Error()}
	}
	return Status{Agent: name, Installed: true, Path: path, Note: "rules written"}
}

// wireEditorExclusions hides .kern from file trees in global editor settings
// (VS Code, Cursor, Antigravity) without affecting file accessibility.
func wireEditorExclusions() []Status {
	var out []Status
	paths := []string{
		homeConfig(".cursor", "User", "settings.json")(""),
		homeConfig(".config", "Code", "User", "settings.json")(""),
	}
	for _, p := range paths {
		// Only configure if the editor's config folder exists or file exists
		if _, err := os.Stat(filepath.Dir(p)); err != nil {
			continue
		}
		var m map[string]any
		data, err := os.ReadFile(p)
		if err == nil {
			cleaned := stripJSONC(data)
			if len(strings.TrimSpace(string(cleaned))) > 0 {
				_ = json.Unmarshal(cleaned, &m)
			}
		}
		if m == nil {
			m = map[string]any{}
		}
		excludes, _ := m["files.exclude"].(map[string]any)
		if excludes == nil {
			excludes = map[string]any{}
		}
		if val, ok := excludes["**/.kern"].(bool); ok && val {
			continue // already excluded
		}
		excludes["**/.kern"] = true
		m["files.exclude"] = excludes
		outData, err := json.MarshalIndent(m, "", "  ")
		if err != nil {
			continue
		}
		if err := os.WriteFile(p, append(outData, '\n'), writePerm(p)); err == nil {
			out = append(out, Status{Agent: "editor-exclude", Installed: true, Path: p, Note: "hidden .kern from editor file tree"})
		}
	}
	return out
}
