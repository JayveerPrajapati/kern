func TestIsGeneratedPath(t *testing.T) {
	generated := []string{
		"api/foo.pb.go",
		"api/foo_grpc.pb.go",
		"api/foo.pulsar.go",
		"internal/mocks/mock_store.go",
		"internal/mocks/expected_mocks.go",
		"generated/mock_client.go",
		"schema/types.generated.ts",
		"schema/types.gen.js",
		"schema/model.pb.js",
		"proto/foo_pb2.py",
		"proto/foo_pb2_grpc.py",
		"build/foo.pb.cc",
		"app/foo.g.cs",
		"app/FooGrpc.cs",
		"generated/FooOuterClass.java",
		"generated/BarGrpc.java",
		"proto/foo.pb.swift",
		"models/foo.g.dart",
		"models/foo.freezed.dart",
		"models/foo.chopper.dart",
		"vendor/foo.min.js",
		"dist/bundle.min.mjs",
		"src/foo.generated.rs",
	}
	for _, p := range generated {
		if !IsGeneratedPath(p) {
			t.Errorf("IsGeneratedPath(%q) = false, want true", p)
		}
	}
	handWritten := []string{
		"main.go",
		"internal/store/store.go",
		"store_mock_adapter.go", // _mock in the middle, not the suffix
		"components/Button.tsx",
		"app/helpers.py",
		"src/notgenerated.rs",
	}
	for _, p := range handWritten {
		if IsGeneratedPath(p) {
			t.Errorf("IsGeneratedPath(%q) = true, want false", p)
		}
	}
}

func TestIsGeneratedContent(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want bool
	}{
		{
			name: "go code generated banner",
			src:  "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
			want: true,
		},
		{
			name: "go docstring containing phrase",
			src:  "// This helper generates code at runtime; do not edit it manually.\npackage main\n",
			want: false,
		},
		{
			name: "atsign generated marker",
			src:  "// @generated SignedSource<<abc123>>\n\nexport const x = 1;\n",
			want: true,
		},
		{
			name: "dotnet autogenerated tag",
			src:  "// <auto-generated>\nnamespace Foo { }\n",
			want: true,
		},
		{
			name: "hand-written",
			src:  "package main\n\n// Greet says hello.\nfunc Greet() {}\n",
			want: false,
		},
		{
			name: "generated by running",
			src:  "// Generated by Wrangler by running `wrangler types` (hash: abc)\nexport {};\n",
			want: true,
		},
	}
	for _, c := range cases {
		if got := isGeneratedContent([]byte(c.src)); got != c.want {
			t.Errorf("%s: isGeneratedContent = %v, want %v", c.name, got, c.want)
		}
	}
}

func TestIsIndexableLongLineGoAndMarkdown(t *testing.T) {
	var goTable strings.Builder
	goTable.WriteString("package main\n")
	for i := 0; i < 12; i++ {
		goTable.WriteString("\"cmd")
		goTable.WriteString(strings.Repeat("x", 40))
		goTable.WriteString("\": {run: func(cmd string, rest []string) int { return 0 }, help: ")
		goTable.WriteString(strings.Repeat("h", 500))
		goTable.WriteString("},\n")
	}
	if !langparse.IsIndexable("cmd/kern/dispatch_table.go", []byte(goTable.String())) {
		t.Error("long-line Go dispatch table must stay indexable (was misclassified as minified)")
	}

	var md strings.Builder
	md.WriteString("# Catalog\n")
	for i := 0; i < 12; i++ {
		md.WriteString("| ")
		md.WriteString(strings.Repeat("c", 600))
		md.WriteString(" |\n")
	}
	if !langparse.IsIndexable("docs/tool-catalog.md", []byte(md.String())) {
		t.Error("long-line Markdown catalog must stay indexable (was misclassified as minified)")
	}

	// The gate must not weaken real minified-bundle rejection for JS/CSS.
	jsBundle := strings.Repeat("x", 600) + "\n" + strings.Repeat("y", 600) + "\n" + strings.Repeat("z", 600) + "\n" + strings.Repeat("w", 600) + "\n" + strings.Repeat("v", 600) + "\n" + strings.Repeat("u", 600) + "\n" + strings.Repeat("t", 600) + "\n" + strings.Repeat("s", 600) + "\n" + strings.Repeat("r", 600) + "\n" + strings.Repeat("q", 600) + "\n" + strings.Repeat("p", 600) + "\n"
	if langparse.IsIndexable("vendor/bundle.min.js", []byte(jsBundle)) {
		t.Error("minified JS bundle must stay rejected")
	}
	if langparse.IsIndexable("vendor/bundle.min.css", []byte(jsBundle)) {
		t.Error("minified CSS bundle must stay rejected")
	}
}

func TestBuildMarksGeneratedFiles(t *testing.T) {
	root := writeTree(t, map[string]string{
		"go.mod":             "module demo\n\ngo 1.22\n",
		"main.go":            "package main\n\nfunc Real() {}\n\nfunc main() { Real() }\n",
		"api/api.pb.go":      "package api\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\nfunc Stub() {}\n",
		"models/types.pb.ts": "// @generated\nexport interface Foo {}\n",
	})
	ix, err := Build(root)
	if err != nil {
		t.Fatal(err)
	}
	if !ix.IsGenerated("api/api.pb.go") {
		t.Error("expected .pb.go path + banner to be marked generated")
	}
	if !ix.IsGenerated("models/types.pb.ts") {
		t.Error("expected .pb.ts path to be marked generated")
	}
	if ix.IsGenerated("main.go") {
		t.Error("main.go should not be marked generated")
	}
}
