// contractsDocRelPath is the repo-relative path (slash-separated) of the
// generated MCP tool contracts document.
const contractsDocRelPath = "docs/mcp/tool-contracts.md"

// contractPhases is the canonical phase order used by the detailed-contracts
// sections, with the established section labels.
var contractPhases = []struct {
	name  string
	label string
}{
	{"explore", "Explore — read / discover"},
	{"plan", "Plan — analyze / simulate"},
	{"edit", "Edit — mutate / execute"},
	{"verify", "Verify — check / validate"},
	{"meta", "Meta — routing"},
	{"cross", "Cross — phase-agnostic utilities"},
}

// contractsRiskOrder is the canonical risk-level order for the at-a-glance
// table.
var contractsRiskOrder = []string{"low", "medium", "high", "critical"}

