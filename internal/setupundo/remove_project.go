// RemoveProject removes kern's project-scope wiring from root — the repo
// files `kern setup` writes inside it (the project half of the
// install/uninstall symmetry; `--remove` without --project is the
// machine-wide undo). Mirrors WireWith's project branch target-for-target,
// with RemoveGlobal's safety contract: merged files keep every non-kern
// byte (backed up first), wholesale files are deleted only when verifiably
// kern's, and .kern data is never touched. Agent-config directories the
// wiring created and the removal left empty (.agents/, .opencode/, ...) are
// pruned too, so a setup→remove round-trip strands nothing (F-A10).
func RemoveProject(root string, opts RemoveOptions) []setup.Status {
	r := &remover{dry: opts.DryRun, agents: opts.Agents}
	if bad := r.unknownAgents(root); len(bad) > 0 {
		return bad
	}
	if opts.HooksOnly {
		r.antigravityProjectHooks(root)
		return r.out
	}
	r.editText("mcp", filepath.Join(root, ".mcp.json"), configstrip.ServerKey("mcpServers"))
	r.dropEmptyJSON("mcp", filepath.Join(root, ".mcp.json"))
	r.editText("AGENTS.md", filepath.Join(root, "AGENTS.md"), stripProjectRules)
	for agent, file := range setup.InstructionFiles {
		if r.want(agent) {
			r.editText(agent+"-instruction", filepath.Join(root, file), stripProjectRules)
		}
	}
	if r.want("opencode") {
		r.editText("opencode", filepath.Join(root, "opencode.json"), configstrip.ServerKey("mcp"))
		r.dropEmptyJSON("opencode", filepath.Join(root, "opencode.json"))
	}
	r.projectPlugin(root)
	r.projectAdapters(root)
	r.projectRuleFiles(root)
	r.antigravityProjectHooks(root)
	r.projectGitBlocks(root)
	r.projectSkills(root)
	// The .kern scaffold, regenerated by the next setup run; config.json
	// stays (persisted wiring choice, not scaffolding).
	r.deleteFile("kern config", filepath.Join(root, ".kern", "profiles.json"), "kern's scaffold")
	// F-A10: a directory the wiring created and the removals above emptied
	// (.agents/, .opencode/, ...) is residue — a fresh setup→remove
	// round-trip must leave nothing behind but .kern data.
	r.pruneEmptyProjectDirs(root)
	return r.out
}

// stripProjectRules removes every kern-managed block from a PROJECT rules
// file: the marked instruction block and the unmarked rules section
// AGENTS.md carries (stripRulesText's shape, project marker pair).
func stripProjectRules(cur string) (string, bool, error) {
	cleaned := strutil.RemoveMarkedBlock(cur, agentwire.InstructionMarkerOpen, agentwire.InstructionMarkerClose)
	cleaned, err := agentwire.RemoveKernSection(cleaned)
	if err != nil {
		return "", false, err
	}
	if cleaned == cur {
		return cur, false, nil
	}
	cleaned = strings.Trim(cleaned, "\r\n")
	if cleaned != "" {
		cleaned += "\n"
	}
	return cleaned, true, nil
}

// dropEmptyJSON deletes a JSON config holding only an empty object (the residue ServerKey leaves).
func (r *remover) dropEmptyJSON(agent, path string) {
	b, err := os.ReadFile(path)
	if err != nil {
		return
	}
	var m map[string]any
	if err := json.Unmarshal(bytes.TrimSpace(configstrip.StripJSONC(b)), &m); err != nil || len(m) != 0 {
		return
	}
	r.deleteFile(agent, path, "held only kern's entry")
}

// projectPlugin deletes the project opencode plugin (shared shipped-copy
// check; mirrors the global plugins()).
func (r *remover) projectPlugin(root string) {
	if r.want("opencode") {
		r.removePluginCopy("opencode-plugin", filepath.Join(root, ".opencode", "plugins", "kern.ts"))
	}
}

// projectAdapters strips kern's MCP entry from repo-scope adapter configs
// (.vscode/mcp.json is shared by the vscode and copilot adapters).
func (r *remover) projectAdapters(root string) {
	seen := map[string]bool{}
	for _, a := range setup.EffectiveAdapterRefs(root) {
		if a.Scope != "repo" || !r.want(a.Name) {
			continue
		}
		if seen[a.Path] {
			continue
		}
		seen[a.Path] = true
		r.editText(a.Name, a.Path, configstrip.ServerKey(a.Key))
		r.dropEmptyJSON(a.Name, a.Path)
	}
}

// projectRuleFiles deletes the kern-owned per-agent rule files setup writes
// wholesale (the cursor instruction rule is a marked block, handled above).
func (r *remover) projectRuleFiles(root string) {
	files := []struct{ agent, rel string }{
		{"continue", filepath.Join(".continue", "rules", "kern.md")},
		{"windsurf", filepath.Join(".windsurf", "rules", "kern-first.md")},
		{"kiro", filepath.Join(".kiro", "steering", "kern-first.md")},
		{"cursor", filepath.Join(".cursor", "rules", "kern-hooks.mdc")},
	}
	for _, f := range files {
		if r.want(f.agent) {
			r.deleteFile(f.agent+"-rules", filepath.Join(root, f.rel), "kern's own rule file")
		}
	}
}

// antigravityProjectHooks deletes the project hooks file, but only when it
// is kern's (same content check the kiro hooks removal uses).
func (r *remover) antigravityProjectHooks(root string) {
	if !r.want("antigravity") {
		return
	}
	p := filepath.Join(root, ".agents", "hooks.json")
	r.editText("antigravity-project-hooks", p, configstrip.AntigravityHook)
}

// projectGitBlocks reverses the two git-ignore writes: the .gitignore block and the .git/info/exclude pair.
func (r *remover) projectGitBlocks(root string) {
	r.editText("gitignore", filepath.Join(root, ".gitignore"), func(cur string) (string, bool, error) {
		cleaned := gitblocks.StripGitignoreBlock(cur)
		if cleaned == cur {
			return cur, false, nil
		}
		out := strings.TrimRight(cleaned, "\n")
		if out != "" {
			out += "\n"
		}
		return out, true, nil
	})
	r.editText("local-gitexclude", filepath.Join(root, ".git", "info", "exclude"), stripLocalExclude)
}

// stripLocalExclude removes the "# kern local exclude" + .kern/ pair
// WireLocalGitExclude appends, leaving every other user line.
func stripLocalExclude(cur string) (string, bool, error) {
	lines := strings.Split(cur, "\n")
	kept := make([]string, 0, len(lines))
	changed := false
	for i := 0; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) != "# kern local exclude" {
			kept = append(kept, lines[i])
			continue
		}
		changed = true
		for i+1 < len(lines) && strings.TrimSpace(lines[i+1]) == ".kern/" {
			i++
		}
	}
	if !changed {
		return cur, false, nil
	}
	next := strings.TrimRight(strings.Join(kept, "\n"), "\n")
	if next != "" {
		next += "\n"
	}
	return next, true, nil
}

// projectSkills removes the kern skill copies WireProjectSkills installs
// into every project skill dir — whole-file kern-owned content only;
// customized copies are left in place and reported.
func (r *remover) projectSkills(root string) {
	for _, d := range []string{".agents", ".claude", ".opencode", ".codex", ".github"} {
		dir := filepath.Join(root, d, "skills")
		if _, err := os.Stat(dir); err != nil {
			continue
		}
		del, kept := kernSkillFiles(dir)
		if len(del) == 0 {
			continue
		}
		note := fmt.Sprintf("%d kern skill file(s)", len(del))
		if len(kept) > 0 {
			note += fmt.Sprintf("; %d customized file(s) left in place", len(kept))
		}
		if r.dry {
			r.add("skills (project)", dir, true, "[dry-run] would delete "+note)
			continue
		}
		for _, p := range del {
			if err := os.Remove(p); err != nil {
				r.fail("skills (project)", p, err)
			}
		}
		pruneEmptySkillDirs(dir)
		r.add("skills (project)", dir, true, "deleted "+note)
	}
	for _, p := range cursorSkillFiles(filepath.Join(root, ".cursor", "rules")) {
		r.deleteFile("skills-cursor (project)", p, "kern-generated skill rule")
	}
}

// projectAgentDirs are the top-level agent-config directories project wiring
// writes into (F-A10): when removal empties one of them, the empty directory
// itself is residue — `kern setup --remove --project` used to leave empty
// .agents/ and .opencode/ behind. .kern is deliberately absent: its data
// (index, persisted config) stays by documented contract.
var projectAgentDirs = []string{
	".agents", ".claude", ".codex", ".continue", ".cursor", ".gemini",
	".github", ".kiro", ".opencode", ".vscode", ".windsurf",
}

// pruneEmptyProjectDirs removes the agent-config directories project wiring
// created once their kern-owned contents are gone. A directory is only ever
// removed when it is EMPTY after the file removals above, so user content
// always wins; .kern data is never a candidate. Skipped entirely in dry-run:
// the deletions it would reverse did not happen, so the dirs are not empty
// yet (the file-level preview already lists everything that would go).
func (r *remover) pruneEmptyProjectDirs(root string) {
	if r.dry {
		return
	}
	for _, d := range projectAgentDirs {
		dir := filepath.Join(root, d)
		if !pruneEmptyDirTree(dir) {
			continue
		}
		r.add("dirs (project)", dir, true, "removed now-empty "+d+"/ (held only kern-generated content)")
	}
}

// pruneEmptyDirTree removes dir and its now-empty subdirectories bottom-up,
// reporting whether dir itself was removed. os.Remove refuses a non-empty
// directory, so a single surviving file anywhere under dir keeps the tree; a
// symlinked dir (or a symlink inside it) is never followed and never
// removed.
func pruneEmptyDirTree(dir string) bool {
	info, err := os.Lstat(dir)
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return false
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		// DirEntry.IsDir is false for symlinks, so the recursion never
		// follows a link; a linked dir keeps its parent non-empty.
		if e.IsDir() {
			pruneEmptyDirTree(filepath.Join(dir, e.Name()))
		}
	}
	// Re-read: the recursive pass may have emptied us.
	entries, err = os.ReadDir(dir)
	if err != nil || len(entries) > 0 {
		return false
	}
	return os.Remove(dir) == nil
}
